"""Generate the leaf-sprig artwork (two-tone lanceolate leaves on a curved stem).

Writes src/components/Sprig.tsx (site) and motion/sprig.svg (video). Colors come from CSS vars
--leaf-1 (light half), --leaf-2 (dark half), --leaf-vein and --stem, so each theme sets its own palette.
"""
import math

def qb(p0, p1, p2, t):
    return tuple((1 - t) ** 2 * a + 2 * (1 - t) * t * b + t ** 2 * c for a, b, c in zip(p0, p1, p2))

def qb_tan(p0, p1, p2, t):
    dx = 2 * (1 - t) * (p1[0] - p0[0]) + 2 * t * (p2[0] - p1[0])
    dy = 2 * (1 - t) * (p1[1] - p0[1]) + 2 * t * (p2[1] - p1[1])
    return math.degrees(math.atan2(dx, -dy))  # 0 = pointing up

def leaf(x, y, rot, s):
    # lanceolate leaf pointing up from (0,0), length 100, slight bend to the right
    light = "M0 0C22 -14 31 -50 7 -100C4 -62 2 -30 0 0Z"
    dark = "M0 0C-20 -16 -27 -56 7 -100C4 -62 2 -30 0 0Z"
    vein = "M0 0Q3 -48 7 -100"
    t = f"translate({x:.1f} {y:.1f}) rotate({rot:.1f}) scale({s:.2f})"
    return (f'<g transform="{t}"><path d="{dark}" fill="var(--leaf-2)"/><path d="{light}" fill="var(--leaf-1)"/>'
            f'<path d="{vein}" fill="none" stroke="var(--leaf-vein)" stroke-width="1.6" stroke-linecap="round"/></g>')

P0, P1, P2 = (100, 300), (82, 160), (112, 18)
parts = [f'<path d="M{P0[0]} {P0[1]}Q{P1[0]} {P1[1]} {P2[0]} {P2[1]}" fill="none" stroke="var(--stem)" stroke-width="4" stroke-linecap="round"/>']
spec = [(.12, 1, 1.15), (.28, -1, 1.1), (.44, 1, 1.0), (.6, -1, .9), (.75, 1, .76), (.87, -1, .62)]
for t, side, s in spec:
    x, y = qb(P0, P1, P2, t); a = qb_tan(P0, P1, P2, t)
    parts.append(leaf(x, y, a + side * 46, s))
x, y = qb(P0, P1, P2, 1); parts.append(leaf(x, y, qb_tan(P0, P1, P2, 1), .5))
inner = ''.join(parts)

open('motion/sprig.svg', 'w').write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="-30 -40 260 350">{inner}</svg>\n')
jsx = inner.replace('stroke-width', 'strokeWidth').replace('stroke-linecap', 'strokeLinecap')
open('src/components/Sprig.tsx', 'w').write(
    "// Generated by scripts/gen_sprig.py: two-tone leaf sprig. Colors: --leaf-1, --leaf-2, --leaf-vein, --stem.\n"
    "export default function Sprig({ className }: { className?: string }) {\n"
    "  return (\n"
    f'    <svg className={{className}} viewBox="-30 -40 260 350" aria-hidden="true" focusable="false">\n      {jsx}\n    </svg>\n'
    "  )\n}\n")
print('ok', len(inner))
